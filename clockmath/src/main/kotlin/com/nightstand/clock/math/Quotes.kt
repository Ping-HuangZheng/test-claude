    val all: List<Quote> = bible.indices.flatMap { i -> listOf(bible[i], analects[i], laozi[i]) }

    /** 某個時間點該顯示第幾句：每 [intervalMinutes] 分鐘換下一句，到底後從頭開始。 */
    fun indexAt(epochMillis: Long, intervalMinutes: Int = DEFAULT_INTERVAL_MINUTES, count: Int = all.size): Int {
        require(intervalMinutes > 0) { "intervalMinutes 必須大於 0" }
        require(count > 0) { "count 必須大於 0" }
        val slot = Math.floorDiv(epochMillis, intervalMinutes * 60_000L)
        return Math.floorMod(slot, count.toLong()).toInt()
    }

    fun at(epochMillis: Long, intervalMinutes: Int = DEFAULT_INTERVAL_MINUTES): Quote =
        all[indexAt(epochMillis, intervalMinutes)]

